    public PixelFont(GraphicsDevice device)
    {
        int count = Glyphs.Count;
        int texW = count * Advance;
        var data = new Color[texW * GlyphH];
        int i = 0;
        foreach (var (ch, rows) in Glyphs)
        {
            for (int y = 0; y < GlyphH; y++)
                for (int x = 0; x < GlyphW; x++)
                    if (rows[y][x] == '#')
                        data[y * texW + i * Advance + x] = Color.White;
            _rects[ch] = new Rectangle(i * Advance, 0, GlyphW, GlyphH);
            i++;
        }
        _atlas = new Texture2D(device, texW, GlyphH);
        _atlas.SetData(data);
    }

    public static string[] GlyphRows(char ch)
        => Glyphs.TryGetValue(char.ToUpperInvariant(ch), out var rows) ? rows : null;

    public static Dictionary<char, Color> GlyphPalette(Color color)
    {
        var d = new Dictionary<char, Color> { ['#'] = color, ['.'] = new Color(0, 0, 0, 0) };
        return d;
    }

    public void Draw(SpriteBatch batch, string text, int x, int y, Color color, int scale = 2)
    {
        int cx = x;
        foreach (var raw in text)
        {
            char ch = char.ToUpperInvariant(raw);
            if (ch == '\n') continue;
            if (_rects.TryGetValue(ch, out var src))
                batch.Draw(_atlas, new Rectangle(cx, y, GlyphW * scale, GlyphH * scale), src, color);
            else if (ch != ' ')
                batch.Draw(_atlas, new Rectangle(cx, y, GlyphW * scale, GlyphH * scale), _rects['?'], color);
            cx += Advance * scale;
        }
    }

    public int Width(string text, int scale = 2)
        => text.Length == 0 ? 0 : text.Length * Advance * scale - scale;

    public int Height(int scale = 2) => GlyphH * scale;
